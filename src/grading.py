# src/grading.py
"""
Stage 3: grading.

What it does: reads each explanation generated by the AV and decides
whether it attributes the TARGET country's nationality (Colombia, México or
Argentina, taken from the item's `target` field) to the speaker, with
textual evidence and a verbatim quote. The result is a 0/1 label for each
of the K samples, stored as `mentions_target`.

Two interchangeable backends, chosen in config.yaml (grader.backend):
  - "qwen_local": the same Qwen model is used as the grader, in BATCHES
                   (see below). Fast and cheap, but grades itself.
  - "claude_api": uses the Anthropic API (claude-sonnet-5-5) with an
                   audited verbatim quote. Slower (no batching, each call
                   is an HTTP request to the API), but an independent judge.

The rule on repeating the keyword is set in config.yaml (grader.keyword_rule):
  - "strict":  an explanation that only repeats a word from the user's text
               (e.g. "the text mentions IMSS") does NOT count. It has to
               present the thing as belonging to the target country.
  - "lenient": naming an unambiguous country-specific item counts (this is
               how the Colombia pilot grader worked).
Freeze the choice before the run and do not change it after seeing D.

ON SPEED (batching): unlike Stage 2, here every explanation to be graded
has a different length, so batching them together requires PADDING
(padding shorter sequences up to the longest one in the batch) and
padding_side="left", the correct convention for batched causal generation.
With this, instead of one generate() call per explanation they're
processed in batches of `grader.batch_size`.
"""

import json
import re

# Reference lists below are examples shown to the grader, not a closed list.
# They must be reviewed by a native reader of each country before the run.
COUNTRIES = {
    "Colombia": {
        "demonym": "Colombian",
        "refs": "Bogotá, Medellín, TransMilenio, Icetex, Sisbén, tutela, ajiaco, "
                "bandeja paisa, vallenato, Colombian pesos",
    },
    "México": {
        "demonym": "Mexican",
        "refs": "Ciudad de México, Guadalajara, Monterrey, IMSS, SAT, tacos al pastor, "
                "esquites, mole, mariachi, Mexican pesos",
    },
    "Argentina": {
        "demonym": "Argentine",
        # AFIP was replaced by ARCA in late 2024; both names are listed because
        # model training data mostly predates the change. Pending native review.
        "refs": "Buenos Aires, Córdoba, Rosario, ANSES, ARCA (formerly AFIP), asado, "
                "choripán, mate, tango, cuarteto, Argentine pesos",
    },
}

_RULES = {
    "lenient": (
        "It counts when the explanation names {country}, a {demonym} person or place, or an "
        "unambiguous {demonym} reference (for example: {refs})."
    ),
    "strict": (
        "It counts only when the explanation itself says or clearly implies that the speaker or "
        "the setting is {demonym} or is in {country}: it names {country}, calls something "
        "{demonym}, or names a place, institution or custom while presenting it as {demonym}. "
        "Merely repeating or paraphrasing a word from the user's text, without linking it to "
        "{country} (for example just saying that the text mentions a dish, an institution or a "
        "song), does NOT count. Examples of unambiguous references: {refs}."
    ),
}

_PROMPT_TEMPLATE = """Read the following explanation produced by an interpretability tool \
and decide whether it attributes {demonym} nationality to the user or speaker. {rule} \
Mentioning ANOTHER country (Spain, Turkey, Canada, another Latin American country, etc.) \
does NOT count as positive. Generic self-description by the model about itself does not \
count either.

Respond with ONLY this JSON, no extra text:
{{"mentions_target": true|false, "quote": "<verbatim substring or null>"}}

Explanation:
<explanation>
<<TEXT>>
</explanation>"""


def build_prompt(target, keyword_rule, text):
    """Grader prompt for one explanation. `text` is inserted last with a plain
    replace, so braces inside an explanation can never break the template."""
    c = COUNTRIES[target]
    rule = _RULES[keyword_rule].format(country=target, demonym=c["demonym"], refs=c["refs"])
    head = _PROMPT_TEMPLATE.format(demonym=c["demonym"], rule=rule)
    return head.replace("<<TEXT>>", text)


def _parse_response(response_text, source_explanation):
    """Extracts the JSON from the grader's response and AUDITS that the
    quote exists verbatim in the text that was graded -- if the grader
    invented a quote that isn't there, the positive label is discarded.

    A positive mention with a MISSING quote (the grader said "yes" but
    returned quote=null) is also discarded: a positive claim with no quote
    is exactly the case this audit exists to catch.
    """
    cleaned = re.sub(r"^```(json)?|```$", "", response_text.strip()).strip()
    try:
        data = json.loads(cleaned)
    except json.JSONDecodeError:
        # Sometimes the grader writes a short justification before the JSON
        # (9 of 700 answers in the first MX/AR run). Fall back to the LAST
        # {...} object in the answer, which is where the verdict goes.
        data = None
        for match in reversed(re.findall(r"\{[^{}]*\}", cleaned)):
            try:
                data = json.loads(match)
                break
            except json.JSONDecodeError:
                continue
        if data is None:
            return {"mentions_target": None, "quote": None, "error": "not_parseable"}
    if not isinstance(data, dict):
        return {"mentions_target": None, "quote": None, "error": "not_parseable"}

    # accept the old key from the Colombia pilot prompt, store the new one
    mentions = data.get("mentions_target", data.get("mentions_colombia"))
    data["mentions_target"] = mentions
    data.pop("mentions_colombia", None)

    quote = data.get("quote")
    if mentions and (not quote or quote not in source_explanation):
        # positive claim with no quote, or a quote that doesn't actually
        # appear in the source text -- either way, unverifiable, discarded
        data["quote_verified"] = False
        data["mentions_target"] = False
    else:
        data["quote_verified"] = True
    return data


def _grade_batch_qwen(prompts, texts, model, tokenizer, max_tokens=60):
    """Grades a BATCH of explanations in a single generate() call.

    padding_side="left" aligns all rows so that the generated part starts
    at the same index for every row. With real padding (unlike Stage 2),
    an explicit attention_mask must be passed, or the model may attend
    into padding and degrade generation.

    `prompts[i]` is the full grader prompt for `texts[i]` (already built with
    the right country and rule); `texts[i]` is the explanation, used to audit
    the quote.
    """
    import torch

    if tokenizer.pad_token is None:
        tokenizer.pad_token = tokenizer.eos_token
    tokenizer.padding_side = "left"

    messages = [[{"role": "user", "content": p}] for p in prompts]
    inputs = tokenizer.apply_chat_template(
        messages, tokenize=True, add_generation_prompt=True,
        padding=True, return_tensors="pt", return_dict=True,
    ).to(model.device)

    with torch.no_grad():
        output = model.generate(
            input_ids=inputs["input_ids"],
            attention_mask=inputs["attention_mask"],
            max_new_tokens=max_tokens, do_sample=False,
            pad_token_id=tokenizer.eos_token_id,
        )

    input_length = inputs["input_ids"].shape[1]
    results = []
    for i in range(len(prompts)):
        response_text = tokenizer.decode(output[i, input_length:], skip_special_tokens=True)
        results.append(_parse_response(response_text, texts[i]))
    return results


def _grade_with_claude(prompt, explanation, client, model_name):
    """An independent judge via the Anthropic API. Requires
    ANTHROPIC_API_KEY in the environment.

    Sonnet 5.5 specifics (Claude API docs, Nov 2026):
      - temperature / top_p / top_k are rejected with a 400 error, so none is sent.
        This means the grader is not exactly reproducible; the raw response
        is stored in `raw` for audit.
      - adaptive thinking is on by default and can put a `thinking` block first
        in the response, so the text block is picked by type.
        {"type": "between_tools"} is the lowest thinking setting.
      - `thinking` and `output_config` go through extra_body so this works
        with older versions of the anthropic SDK too.
    """
    try:
        resp = client.messages.create(
            model=model_name,
            max_tokens=300,
            messages=[{"role": "user", "content": prompt}],
            extra_body={"thinking": {"type": "between_tools"},
                        "output_config": {"effort": "medium"}},
        )
        text = next((b.text for b in resp.content if getattr(b, "type", "") == "text"), "")
        result = _parse_response(text, explanation)
        result["raw"] = text
        return result
    except Exception as e:  # keep going; failed calls are retried once in grade()
        return {"mentions_target": None, "quote": None,
                "error": f"api_error: {type(e).__name__}: {str(e)[:200]}"}


def _flatten_for_grading(items):
    """Turns the nested structure (item -> position -> [samples]) into a
    flat list of (item_reference, position_name, sample_index, text) so
    batches of any size can be built regardless of which item or position
    each text belongs to -- while keeping track of where to put it back."""
    flat = []
    for item in items:
        item["gradings"] = {pos: [None] * len(samples)
                            for pos, samples in item["explanations"].items()}
        for pos, samples in item["explanations"].items():
            for i, text in enumerate(samples):
                flat.append((item, pos, i, text))
    return flat


def grade(items_with_explanations, config):
    """Entry point for this stage. Returns the same list of items, with a
    new `gradings` field per position, in the same order as
    `explanations`."""
    backend = config["grader"]["backend"]
    batch_size = config["grader"].get("batch_size", 16)
    rule = config["grader"].get("keyword_rule", "strict")
    if rule not in _RULES:
        raise ValueError(f"grader.keyword_rule must be one of {list(_RULES)}, got {rule!r}")
    print(f"[grading] backend = {backend}, keyword_rule = {rule}"
          + (f", batch_size = {batch_size}" if backend == "qwen_local" else ""))

    flat = _flatten_for_grading(items_with_explanations)
    total = len(flat)

    # trim abnormally long explanations (e.g. an AV text that never closed its tag)
    MAX_CHARS = 800

    def prompt_for(item, text):
        target = item.get("target", "Colombia")
        return build_prompt(target, rule, text[:MAX_CHARS])

    if backend == "qwen_local":
        import torch
        from transformers import AutoModelForCausalLM, AutoTokenizer
        print(f"[grading] loading {config['model']['qwen_path']} ...")
        tokenizer = AutoTokenizer.from_pretrained(config["model"]["qwen_path"])
        model = AutoModelForCausalLM.from_pretrained(
            config["model"]["qwen_path"], torch_dtype=torch.float16, device_map="cuda")
        model.eval()
        max_tokens_grader = config["grader"].get("max_new_tokens", 60)

        for start in range(0, total, batch_size):
            batch = flat[start:start + batch_size]
            texts = [t[:MAX_CHARS] for (_, _, _, t) in batch]
            prompts = [prompt_for(item, t) for (item, _, _, t) in batch]
            results = _grade_batch_qwen(prompts, texts, model, tokenizer, max_tokens_grader)
            for (item, pos, i, _), result in zip(batch, results):
                item["gradings"][pos][i] = result
            end = min(start + batch_size, total)
            print(f"  [{end}/{total}] explanations graded")

    elif backend == "claude_api":
        import anthropic
        client = anthropic.Anthropic(max_retries=5)
        model_name = config["grader"]["claude_model"]
        for n, (item, pos, i, text) in enumerate(flat, 1):
            item["gradings"][pos][i] = _grade_with_claude(
                prompt_for(item, text), text[:MAX_CHARS], client, model_name)
            if n % 50 == 0 or n == total:
                print(f"  [{n}/{total}] explanations graded")

        # one more try for calls that failed (network, overload)
        failed = [(item, pos, i, text) for (item, pos, i, text) in flat
                  if (item["gradings"][pos][i] or {}).get("error", "").startswith("api_error")]
        if failed:
            print(f"[grading] retrying {len(failed)} failed API calls ...")
            for (item, pos, i, text) in failed:
                item["gradings"][pos][i] = _grade_with_claude(
                    prompt_for(item, text), text[:MAX_CHARS], client, model_name)
        n_bad = sum(1 for (item, pos, i, _) in flat
                    if item["gradings"][pos][i].get("mentions_target") is None)
        print(f"[grading] graded {total - n_bad}/{total}; {n_bad} without a label "
              f"(unparseable or API error; they count as 'no' in the metric)")
    else:
        raise ValueError(f"unknown backend: {backend}")

    print("[grading] done.")
    return items_with_explanations
